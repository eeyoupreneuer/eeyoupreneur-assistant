// Turns everything in the /knowledge folder into one text bundle the assistant reads.
// Supports .md, .txt, .pdf and .docx. Run with: npm run build
import { readdir, readFile, writeFile, mkdir, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const KNOWLEDGE_DIR = path.join(root, "knowledge");
const OUT_DIR = path.join(root, "netlify", "functions", "_generated");
const OUT_FILE = path.join(OUT_DIR, "knowledge.mjs");

// Roughly 150k tokens. Past this, answers get slower and costlier; see README.
const SOFT_LIMIT_CHARS = 600_000;

async function listFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".") || entry.name.startsWith("_")) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await listFiles(full)));
    else out.push(full);
  }
  return out.sort();
}

async function extractText(file) {
  const ext = path.extname(file).toLowerCase();
  if (ext === ".md" || ext === ".txt") return readFile(file, "utf8");
  if (ext === ".docx") {
    const mammoth = (await import("mammoth")).default;
    const { value } = await mammoth.extractRawText({ path: file });
    return value;
  }
  if (ext === ".pdf") {
    const { extractText: pdfText, getDocumentProxy } = await import("unpdf");
    const pdf = await getDocumentProxy(new Uint8Array(await readFile(file)));
    const { text } = await pdfText(pdf, { mergePages: true });
    return text;
  }
  return null; // unsupported type, skipped
}

function clean(text) {
  return text
    .replace(/\r\n/g, "\n")
    .replace(/[ \t]+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

const files = await listFiles(KNOWLEDGE_DIR).catch(() => []);
const docs = [];
const skipped = [];

for (const file of files) {
  const rel = path.relative(KNOWLEDGE_DIR, file);
  if (path.basename(file).toLowerCase() === "readme.md") continue;
  try {
    const raw = await extractText(file);
    if (raw == null) { skipped.push(`${rel} (unsupported type)`); continue; }
    const text = clean(raw);
    if (text.length < 20) { skipped.push(`${rel} (no readable text — scanned PDF?)`); continue; }
    const { mtime } = await stat(file);
    docs.push({ rel, text, updated: mtime.toISOString().slice(0, 10) });
  } catch (err) {
    skipped.push(`${rel} (error: ${err.message})`);
  }
}

const bundle = docs
  .map((d) => `<document source="${d.rel}" file_updated="${d.updated}">\n${d.text}\n</document>`)
  .join("\n\n");

await mkdir(OUT_DIR, { recursive: true });
await writeFile(
  OUT_FILE,
  `// AUTO-GENERATED by scripts/build-knowledge.mjs — do not edit by hand.\n` +
    `export const KNOWLEDGE = ${JSON.stringify(bundle)};\n` +
    `export const SOURCES = ${JSON.stringify(docs.map((d) => d.rel))};\n`
);

const total = bundle.length;
console.log(`\nKnowledge bundle built: ${docs.length} document(s), ${total.toLocaleString()} characters (~${Math.round(total / 4).toLocaleString()} tokens)`);
for (const d of docs) console.log(`  ✓ ${d.rel}  (${d.text.length.toLocaleString()} chars)`);
for (const s of skipped) console.log(`  ✗ skipped ${s}`);
if (total > SOFT_LIMIT_CHARS) {
  console.warn(`\n⚠ The bundle is over ~150k tokens. It will still work, but each answer costs more.`);
  console.warn(`  Trim long documents, or keep only the parts entrepreneurs actually need.`);
}
